export type MessageKey = keyof typeof zh;
/** The current interface language for shared widgets that are not given one. */
export const LanguageContext = createContext<Language>("zh");
export function t(
  language: Language,
  key: MessageKey,
  params?: Record<string, string | number>,
): string {
  let text: string = language === "en" ? en[key] : language === "zhtw" ? zhtw[key] : zh[key];
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      text = text.replaceAll(`{${k}}`, String(v));
    }
  }
  return text;
}

const phaseKeys: Record<string, MessageKey> = {
  stopped: "stopped", starting: "starting", running: "running", stopping: "stopping",
  recovering: "recovering", failed: "failed", shutdown: "shutdown",
};
export function phaseLabel(language: Language, phase: string): string {
  return phaseKeys[phase] ? t(language, phaseKeys[phase]) : phase;
}

export function connectionLabel(language: Language, connection: Connection): string {
  return t(language, connection);
}
