// The interface language is an instance preference on the service (shared with
// the desktop client); this origin keeps a copy for the login page. The fallback
// and regional aliases follow upstream i18n.
import { createContext } from "react";
import type { Connection } from "./api";

export type Language = "zh" | "en" | "zhtw";
const STORAGE_KEY = "mihomo-server-language";

export function resolveLanguage(value?: string | null): Language {
  const normalized = value?.toLowerCase().replaceAll("_", "-") || "";
  if (normalized === "en" || normalized.startsWith("en-")) return "en";
  if (
    normalized === "zhtw" ||
    normalized === "zh-tw" ||
    normalized === "zh-hk" ||
    normalized === "zh-hant" ||
    normalized === "zh-mo" ||
    normalized === "zh-cht"
  ) {
    return "zhtw";
  }
  return "zh";
}

export function savedLanguage(): Language {
  try { return resolveLanguage(window.localStorage.getItem(STORAGE_KEY)); }
  catch { return "zh"; }
}

export function saveLanguage(language: Language) {
  try { window.localStorage.setItem(STORAGE_KEY, language); }
  catch { /* Private browser storage can be unavailable. */ }
}

